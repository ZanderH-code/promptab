import { expect, test } from '@playwright/test'
import { openTab, seedExistingUser, templateBookmarks } from './helpers'

for (const preset of ['Paper', 'Tide'] as const) {
  test(`dashboard widgets align with ${preset} preset`, async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 800 })
    await page.clock.install({ time: new Date('2026-08-01T19:17:00Z') })
    await seedExistingUser(page, { language: 'en', shortcuts: templateBookmarks.slice(0, 3), columns: 3, showSearch: false })
    await page.route('**/favicon.ico', route => route.abort())
    await page.route('https://geocoding-api.open-meteo.com/**', route => route.fulfill({ json: { results: [{ id: 1, name: 'Portland', country: 'United States', latitude: 45.52, longitude: -122.68 }] } }))
    await page.route('https://api.open-meteo.com/**', route => route.fulfill({ json: { current: { temperature_2m: 22, weather_code: 2 }, daily: { time: ['2026-08-01', '2026-08-02', '2026-08-03'], weather_code: [2, 1, 3], temperature_2m_max: [24, 26, 23], temperature_2m_min: [15, 16, 14] } } }))
    await page.goto('/')
    await page.locator('.settings-button').click()
    await openTab(page, 'appearance')
    await page.getByRole('button', { name: preset, exact: true }).click()
    await openTab(page, 'layout')
    await page.getByRole('combobox', { name: 'Layout', exact: true }).click()
    await page.getByRole('option', { name: 'Three-column dashboard', exact: true }).click()
    await openTab(page, 'widgets')
    async function moveLast(area: string) {
      await page.getByRole('combobox', { name: 'Widget area', exact: true }).last().click()
      await page.getByRole('option', { name: area, exact: true }).click()
    }
    await page.getByRole('button', { name: 'Weather', exact: true }).click()
    await moveLast('date')
    await page.getByRole('textbox', { name: 'City', exact: true }).fill('Portland')
    await page.getByRole('button', { name: 'Search cities', exact: true }).click()
    await page.getByRole('option', { name: 'Portland, United States' }).click()
    await page.getByRole('button', { name: 'Note', exact: true }).click()
    await page.getByRole('textbox', { name: 'Note content', exact: true }).fill('Make room for the things that matter.')
    await moveLast('search')
    await page.getByRole('button', { name: 'Todo list', exact: true }).click()
    await page.getByRole('button', { name: 'Add todo', exact: true }).click()
    await page.getByRole('textbox', { name: 'Todo item' }).fill('Plan the next adventure')
    await moveLast('links')
    await page.getByRole('button', { name: 'Close settings' }).click()
    const weather = page.locator('[data-widget="weather"]')
    await weather.getByRole('button', { name: 'Update weather' }).click()
    await expect(weather.getByText('22°C')).toBeVisible()
    const clock = await page.locator('[data-widget="clock"]').boundingBox()
    const date = await page.locator('[data-widget="date"]').boundingBox()
    const cards = await Promise.all(['weather', 'note', 'todo'].map(type => page.locator(`[data-widget="${type}"]`).boundingBox()))
    expect(date!.y).toBeGreaterThanOrEqual(clock!.y + clock!.height - 1)
    expect(date!.y - (clock!.y + clock!.height)).toBeLessThan(20)
    const clockText = await page.locator('.clock').boundingBox()
    const dateText = await page.locator('.mnt-date').boundingBox()
    expect(Math.abs((clockText!.x + clockText!.width / 2) - (dateText!.x + dateText!.width / 2))).toBeLessThan(2)
    expect(cards[1]!.x - (cards[0]!.x + cards[0]!.width)).toBeGreaterThanOrEqual(15)
    expect(Math.max(...cards.map(card => card!.y)) - Math.min(...cards.map(card => card!.y))).toBeLessThan(2)
    await expect(page.locator('.mnt-layout')).toHaveScreenshot(`dashboard-widgets-${preset.toLowerCase()}.png`)
  })
}
