import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { readBookmarkGroups, seedBookmarkFolders } from './bookmark-folder-fixture'

test('folders preserve bookmarks and support keyboard, backdrop, links, menus and accessibility', async ({ page }) => {
  await seedBookmarkFolders(page)
  const before = await readBookmarkGroups(page)
  const opener = page.getByRole('button', { name: 'Open folder Work Folder with 2 bookmarks' })
  await expect(page.getByRole('link', { name: 'First Link' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Second Link' })).toHaveCount(0)
  await expect(opener).toHaveAttribute('aria-expanded', 'false')
  await opener.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Work Folder' })
  await expect(dialog).toBeVisible()
  await expect(page.locator('html')).toHaveCSS('overflow', 'hidden')
  await expect(opener).toHaveAttribute('aria-expanded', 'true')
  const second = dialog.getByRole('link', { name: 'Second Link' })
  const third = dialog.getByRole('link', { name: 'Third Link' })
  const close = dialog.getByRole('button', { name: 'Close folder' })
  await expect(second).toBeFocused()
  await expect(second).toHaveAttribute('href', 'https://example.com/second')
  await close.focus()
  await page.keyboard.press('Shift+Tab')
  await expect(third).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('e')
  await expect(page.locator('.edit-toolbar')).toHaveCount(0)
  const results = await new AxeBuilder({ page }).include('.mnt-folder-dialog').analyze()
  expect(results.violations.filter(item => item.impact === 'serious' || item.impact === 'critical')).toEqual([])
  await dialog.locator('h2').click()
  await expect(dialog).toBeVisible()
  await second.click({ button: 'right' })
  const menu = page.getByRole('menu')
  await expect(menu).toBeVisible()
  await menu.getByRole('menuitem').last().focus()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await expect(second).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  await expect(opener).toHaveAttribute('aria-expanded', 'false')
  await opener.click()
  await page.locator('.mnt-folder-backdrop').click({ position: { x: 3, y: 3 } })
  await expect(dialog).toHaveCount(0)
  expect(await readBookmarkGroups(page)).toEqual(before)
})

test('folder context menu opens all of its bookmarks', async ({ page }) => {
  await seedBookmarkFolders(page)
  await page.evaluate(() => {
    const recorded: string[] = []
    ;(window as Window & { __openedFolderUrls?: string[] }).__openedFolderUrls = recorded
    window.open = ((url?: string | URL) => { recorded.push(String(url)); return null }) as typeof window.open
  })
  await page.getByRole('button', { name: 'Open folder Work Folder with 2 bookmarks' }).click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Open all' }).click()
  expect(await page.evaluate(() => (window as Window & { __openedFolderUrls?: string[] }).__openedFolderUrls)).toEqual(['https://example.com/second', 'https://example.com/third'])
})

test('a very long folder name wraps without pushing the dialog outside a phone viewport', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 740 })
  await seedBookmarkFolders(page)
  const name = 'Long folder name '.repeat(50).trim()
  await page.evaluate(longName => {
    const index = JSON.parse(localStorage.getItem('profiles:v2:index')!)
    const key = `profiles:v2:generation:${index.generation}`
    const snapshot = JSON.parse(localStorage.getItem(key)!)
    snapshot.profiles.profiles[snapshot.profiles.activeProfileId].bookmarks.groups[1].name = longName
    localStorage.setItem(key, JSON.stringify(snapshot))
  }, name)
  await page.reload()
  const opener = page.locator('button.mnt-folder[data-folder="folder-second"]')
  await expect(opener).toHaveAttribute('title', name)
  await opener.click()
  const dialog = page.getByRole('dialog', { name })
  await expect(dialog).toBeVisible()
  const rect = (await dialog.boundingBox())!
  expect(rect.x).toBeGreaterThanOrEqual(0)
  expect(rect.y).toBeGreaterThanOrEqual(0)
  expect(rect.x + rect.width).toBeLessThanOrEqual(360)
  expect(rect.y + rect.height).toBeLessThanOrEqual(740)
})

test('empty folder and group actions work at a 360px viewport', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 740 })
  await seedBookmarkFolders(page)
  const opener = page.getByRole('button', { name: 'Open folder Empty Folder with 0 bookmarks' })
  await opener.focus()
  await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menuitem', { name: 'Open all' })).toBeVisible()
  await page.keyboard.press('Escape')
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Empty Folder' })
  await expect(dialog.getByText('This folder is empty')).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Close folder' })).toBeFocused()
  const rect = await dialog.boundingBox()
  expect(rect).not.toBeNull()
  expect(rect!.x).toBeGreaterThanOrEqual(0)
  expect(rect!.x + rect!.width).toBeLessThanOrEqual(360)
  expect(rect!.y).toBeGreaterThanOrEqual(0)
  expect(rect!.y + rect!.height).toBeLessThanOrEqual(740)
  await dialog.getByRole('button', { name: 'Close folder' }).click()
  await expect(opener).toBeFocused()
})
